const heroes = cities.map((c) => c.heroDesc);
const uniqueHeroes = new Set(heroes);
if (uniqueHeroes.size < heroes.length) {
  console.error(`WARNING: ${heroes.length - uniqueHeroes.size} duplicate hero descriptions found!`);
} else {
  console.log(`PASS  All ${heroes.length} hero descriptions are unique.`);
}

const locals = cities.map((c) => c.localContent);
const uniqueLocals = new Set(locals);
if (uniqueLocals.size < locals.length) {
  console.error(`WARNING: ${locals.length - uniqueLocals.size} duplicate local content blocks found!`);
} else {
  console.log(`PASS  All ${locals.length} local content blocks are unique.`);
}

const faqKeys = cities.map((c) => c.faqs.map(f => `${f.tpl}-${f.ans}`).sort().join("|"));
const uniqueFaqs = new Set(faqKeys);
if (uniqueFaqs.size < faqKeys.length) {
  console.error(`WARNING: ${faqKeys.length - uniqueFaqs.size} duplicate FAQ combinations found!`);
} else {
  console.log(`PASS  All ${faqKeys.length} FAQ combinations are unique.`);
}

console.log(`\nContent uniqueness validation complete.`);
